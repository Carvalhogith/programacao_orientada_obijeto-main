
public class Musica {

    private String titulo;
    private String artista;

    public Musica(String titulo, String artista) {
        this.titulo = titulo;
        this.artista = artista;
    }

    public String gettitulo() {
        return this.titulo;
    }

    public String getartista() {
        return this.artista;
    }

}
